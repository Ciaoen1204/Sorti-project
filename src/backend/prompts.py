def normalize_persona(user_persona: str | None) -> str:
    if not user_persona:
        return "未提供收納人格"

    persona_name = (
        user_persona.strip()
        .replace("🔮", "")
        .replace("人格：", "")
        .strip()
    )
    persona_name = PERSONA_ALIASES.get(persona_name, persona_name)
    for name in PERSONA_GUIDE:
        if persona_name == name or persona_name.startswith(name + "："):
            return name
    return persona_name


def describe_persona(user_persona: str | None) -> str:
    if not user_persona:
        return "未提供收納人格"

    persona_name = normalize_persona(user_persona)
    description = PERSONA_GUIDE.get(persona_name)

    if not description:
        return persona_name

    return f"{persona_name}：{description}"


def persona_response_focus(user_persona: str | None) -> str:
    persona_name = normalize_persona(user_persona)
    return PERSONA_RESPONSE_FOCUS.get(
        persona_name,
        "回答要根據人格調整收納風格，但避免每次都使用相同話術。",
    )


def _safe_value(
    inputs: dict[str, Any],
    key: str,
    default: str = "未提供",
) -> str:
    value = inputs.get(key)

    if value is None:
        return default

    text = str(value).strip()
    return text or default


